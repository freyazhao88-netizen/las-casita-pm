-- anything worth keeping. Safe to skip if these tables don't exist.
drop table if exists quote_items cascade;
drop table if exists payment_schedules cascade;
drop table if exists quotes cascade;
drop table if exists material_expenses cascade;
drop table if exists project_stages cascade;
drop table if exists quote_categories cascade;
drop table if exists attendance_entries cascade;
drop table if exists project_managers cascade;
drop table if exists workers cascade;
drop table if exists projects cascade;
drop table if exists profiles cascade;

drop type if exists public.quote_calc_mode cascade;
drop type if exists public.quote_status cascade;
drop type if exists public.inspection_status cascade;
drop type if exists public.app_role cascade;
